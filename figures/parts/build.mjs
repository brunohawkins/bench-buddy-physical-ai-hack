// node parts/build.mjs → parts/index.html: the gallery with three.js and every model bundled in,
// so it opens straight from disk and works offline.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const HERE = dirname(fileURLToPath(import.meta.url));
const out = await build({ entryPoints: [join(HERE, "gallery.js")], bundle: true, format: "iife", minify: true, write: false, target: "es2020", legalComments: "none" });
const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const page = readFileSync(join(HERE, "viewer.src.html"), "utf8").replace("<script>/*BUNDLE*/</script>", () => `<script>${js}</script>`);
writeFileSync(join(HERE, "index.html"), page);
console.log("wrote parts/index.html", (page.length / 1024).toFixed(0), "KB");

// The twin widget for the Bench Buddy UI (embed.js), as one ES module next to the UI's other vendored code.
const ui = join(HERE, "..", "..", "ui", "vendor", "twin.bundle.mjs");
const mod = await build({ entryPoints: [join(HERE, "embed.js")], bundle: true, format: "esm", minify: true, write: false, target: "es2020", legalComments: "none" });
writeFileSync(ui, `// Generated by figures/parts/build.mjs from figures/parts/embed.js (three.js, MIT). Do not edit.
${mod.outputFiles[0].text}`);
console.log("wrote ui/vendor/twin.bundle.mjs", (mod.outputFiles[0].text.length / 1024).toFixed(0), "KB");
